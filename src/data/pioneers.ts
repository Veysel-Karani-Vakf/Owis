const PIONEER_PLACEHOLDER_IMAGE = '/programs/yemen-pioneers-hero.jpeg';

function rosterUniversity(entry: PioneerRosterEntry): string | undefined {
  if (!entry.university && !entry.city) return undefined;
  if (!entry.university) return entry.city;
  if (!entry.city || entry.city === entry.university) return entry.university;
  return `${entry.university} — ${entry.city}`;
}

function rosterIntro(locale: Locale, entry: PioneerRosterEntry, cohortName: string): string {
  const university = rosterUniversity(entry);
  if (locale === 'ar') {
    const studyAt = university ? ` في ${university}` : '';
    return `${entry.nameAr} من محافظة ${entry.origin}، ضمن ${cohortName}، ويدرس ${entry.degree} في تخصص ${entry.major}${studyAt}.`;
  }

  if (locale === 'tr') {
    const studyAt = university ? ` — ${university}` : '';
    return `${entry.nameLatin}, ${cohortName} kapsamındaki Yemen Öncüleri bursiyeridir. ${entry.degree}: ${entry.major}${studyAt}.`;
  }

  const studyAt = university ? ` — ${university}` : '';
  return `${entry.nameLatin} is a Yemen Pioneers scholar in the ${cohortName}. ${entry.degree}: ${entry.major}${studyAt}.`;
}

function buildRosterPioneer(
  locale: Locale,
  entry: PioneerRosterEntry,
  existing: Pioneer | undefined,
  cohortName: string,
  order: number,
): Pioneer {
  const intro = rosterIntro(locale, entry, cohortName);
  const university = rosterUniversity(entry);
  const portraitImage = pioneerPortraitBySlug[entry.slug] || entry.image;
  const name = locale === 'ar' ? entry.nameAr : existing?.name || entry.nameLatin;
  const shortName =
    (locale === 'ar' ? entry.shortNameAr : entry.shortNameLatin) ||
    existing?.shortName ||
    existing?.displayName;
  const role = locale === 'ar'
    ? `مبتعث رواد اليمن — ${entry.major}`
    : locale === 'tr'
      ? 'Yemen Öncüleri bursiyeri'
      : 'Yemen Pioneers scholar';

  if (existing) {
    return {
      ...existing,
      id: `pioneer-${entry.slug}`,
      slug: entry.slug,
      cohortId: entry.cohortId,
      cohortName,
      name,
      shortName,
      role,
      image: portraitImage || PIONEER_PLACEHOLDER_IMAGE,
      hasPortrait: Boolean(portraitImage),
      imagePosition: entry.imagePosition || 'center 20%',
      order,
      isPublished: true,
    };
  }

  return {
    id: `pioneer-${entry.slug}`,
    slug: entry.slug,
    cohortId: entry.cohortId,
    cohortName,
    name,
    shortName,
    role,
    image: portraitImage || PIONEER_PLACEHOLDER_IMAGE,
    hasPortrait: Boolean(portraitImage),
    imagePosition: entry.imagePosition || 'center 20%',
    origin: entry.origin,
    university,
    degree: entry.degree,
    major: entry.major,
    shortIntro: intro,
    fullBio: [intro],
    education: [`${entry.degree} — ${entry.major}${university ? ` — ${university}` : ''}`],
    career: [],
    achievements: [],
    programContribution: [],
    order,
    isPublished: true,
  };
}

function withCompleteRoster(base: PioneersPageContent, locale: Locale): PioneersPageContent {
  const existingBySlug = new Map(base.pioneers.map((pioneer) => [pioneer.slug, pioneer]));
  const cohortIds = new Set(pioneersRoster.map((entry) => entry.cohortId));
  const cohorts = base.cohorts.filter((cohort) => cohortIds.has(cohort.id as PioneerRosterEntry['cohortId']));
  const cohortNames = new Map(cohorts.map((cohort) => [cohort.id, cohort.title]));
  const orderByCohort = new Map<string, number>();

  const pioneers = pioneersRoster.map((entry) => {
    const nextOrder = (orderByCohort.get(entry.cohortId) || 0) + 1;
    orderByCohort.set(entry.cohortId, nextOrder);
    return buildRosterPioneer(
      locale,
      entry,
      existingBySlug.get(entry.slug),
      cohortNames.get(entry.cohortId) || entry.cohortId,
      nextOrder,
    );
  });

  return { ...base, cohorts, pioneers };
}

export function getPioneersContent(locale: Locale): PioneersPageContent {
  const base = withCompleteRoster(defaultPioneersData[locale], locale);
  const cmsPioneersRows = cmsRows('library_articles');
  if (!cmsPioneersRows) return base;
  return base;
}

export function getPioneerBySlug(locale: Locale, slug: string): Pioneer | undefined {
  const content = getPioneersContent(locale);
  return content.pioneers.find((p) => p.slug === slug);
}
